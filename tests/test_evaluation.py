@pytest.mark.parametrize("raw, expected", [
    ([True, False], [True, False]),                    # real booleans
    (["True", "False"], [True, False]),                # strings from read_csv
    (["true", "false"], [True, False]),                # lowercase
    ([" True ", "False"], [True, False]),              # stray whitespace
    ([1, 0], [True, False]),                           # numeric
])
def test_label_coercion_handles_every_shape_read_csv_produces(raw, expected):
    """label_is_laundering comes back as dtype=object. A bare `== True`
    comparison happens to work for the committed CSV but returns all-False for
    a string-valued column, which would zero every metric without raising."""
    assert list(_as_bool(pd.Series(raw))) == expected


