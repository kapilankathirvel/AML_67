"""
Tests for evaluation/harness.py — the module that regenerates README.md's
Results table.

Two jobs here:

  1. The metric arithmetic is correct, including the degenerate cases. These
     are pure functions over sets, so they're tested against hand-computed
     confusion matrices rather than against the dataset.

  2. The ground truth still has the shape every published number depends on.
     data/sample/aml_sample.csv is generated by data/generate_synthetic.py with
     a fixed seed; if it is ever regenerated with different parameters, every
     figure in README.md, DOCUMENTATION.md and TRACK_A_PROGRESS.md silently
     becomes wrong. Pinning the counts here turns that into a failing test
     instead of a documentation bug nobody notices.
"""

import pandas as pd
import pytest

from evaluation.harness import (
    GroundTruth,
    evaluate,
    load_ground_truth,
    naive_baseline,
    _as_bool,
)


# ---------------------------------------------------------------------------
# Metric arithmetic
# ---------------------------------------------------------------------------


def test_evaluate_computes_a_known_confusion_matrix():
    population = {"a", "b", "c", "d", "e", "f", "g", "h", "i", "j"}
    positives = {"a", "b", "c", "d"}          # 4 positives, 6 negatives
    flagged = {"a", "b", "e", "f"}            # 2 TP, 2 FP, 2 FN, 4 TN

    m = evaluate(flagged, positives, population)

    assert (m.true_positives, m.false_positives) == (2, 2)
    assert (m.false_negatives, m.true_negatives) == (2, 4)
    assert m.precision == pytest.approx(0.5)          # 2 / (2+2)
    assert m.recall == pytest.approx(0.5)             # 2 / (2+2)
    assert m.f1 == pytest.approx(0.5)
    assert m.false_positive_rate == pytest.approx(2 / 6)


def test_perfect_and_useless_detectors_score_as_expected():
    population = {"a", "b", "c", "d"}
    positives = {"a", "b"}

    perfect = evaluate({"a", "b"}, positives, population)
    assert perfect.precision == 1.0 and perfect.recall == 1.0
    assert perfect.false_positive_rate == 0.0

    flag_everything = evaluate(population, positives, population)
    assert flag_everything.recall == 1.0               # catches everything
    assert flag_everything.precision == pytest.approx(0.5)
    assert flag_everything.false_positive_rate == 1.0  # and is useless


def test_flagging_nobody_scores_zero_not_one():
    """A detector that never fires must not look perfect.

    precision = TP/(TP+FP) is 0/0 here. Returning 1.0 would make "flag nothing"
    the highest-precision strategy available, which is exactly the degenerate
    case the metric exists to expose.
    """
    m = evaluate(set(), {"a", "b"}, {"a", "b", "c"})

    assert m.flagged == 0
    assert m.precision == 0.0
    assert m.recall == 0.0
    assert m.f1 == 0.0
    assert m.false_positive_rate == 0.0


def test_ids_outside_the_population_are_ignored():
    """A flag for an entity absent from the customer roster must not distort
    the confusion matrix — it should be dropped, not counted as a false
    positive against a population it isn't part of."""
    m = evaluate({"a", "ghost"}, {"a"}, {"a", "b"})

    assert m.flagged == 1                     # "ghost" dropped
    assert m.true_positives == 1
    assert m.false_positives == 0
    assert m.true_negatives == 1


# ---------------------------------------------------------------------------
# Label coercion
# ---------------------------------------------------------------------------


@pytest.mark.parametrize("raw, expected", [
    ([True, False], [True, False]),                    # real booleans
    (["True", "False"], [True, False]),                # strings from read_csv
    (["true", "false"], [True, False]),                # lowercase
    ([" True ", "False"], [True, False]),              # stray whitespace
    ([1, 0], [True, False]),                           # numeric
])
def test_label_coercion_handles_every_shape_read_csv_produces(raw, expected):
    """label_is_laundering comes back as dtype=object. A bare `== True`
    comparison happens to work for the committed CSV but returns all-False for
    a string-valued column, which would zero every metric without raising."""
    assert list(_as_bool(pd.Series(raw))) == expected


# ---------------------------------------------------------------------------
# Ground truth shape — guards every published number
# ---------------------------------------------------------------------------


def test_ground_truth_matches_the_documented_counts():
    """If this fails, data/sample/aml_sample.csv was regenerated and every
    metric quoted in README.md and docs/ is stale. Re-run
    `python -m evaluation.run_evaluation` and update the docs from its output."""
    _, gt = load_ground_truth()

    assert len(gt.all_customers) == 270
    assert gt.labelled_txn_count == 202
    assert len(gt.sender_only) == 51
    assert len(gt.sender_or_receiver) == 114
    assert len(gt.receive_only) == 63


def test_receive_only_positives_are_the_documented_recall_gap():
    """The 63 receive-only customers are the reason recall roughly halves
    between the two ground-truth definitions. No rule evaluates fan-in, so
    they are structurally uncatchable rather than merely missed."""
    _, gt = load_ground_truth()

    assert gt.receive_only == gt.sender_or_receiver - gt.sender_only
    assert not (gt.receive_only & gt.sender_only)
    assert gt.receive_only <= gt.all_customers


def test_naive_baseline_flags_almost_everyone():
    """The premise of the whole project: the naive rule has near-perfect recall
    and is useless because of it."""
    df, gt = load_ground_truth()
    naive = naive_baseline(df, gt.all_customers)
    m = evaluate(naive, gt.sender_only, gt.all_customers)

    assert m.recall == 1.0
    assert m.false_positive_rate > 0.9
    assert len(naive) / len(gt.all_customers) > 0.9


def test_positives_accessor_rejects_an_unknown_definition():
    gt = GroundTruth(all_customers={"a"}, sender_only=set(),
                     sender_or_receiver=set(), labelled_txn_count=0)

    with pytest.raises(ValueError, match="unknown ground-truth definition"):
        gt.positives("receiver_only")


# ---------------------------------------------------------------------------
# The harness must never reach the LLM planner
# ---------------------------------------------------------------------------


def test_harness_pins_the_llm_planner_off_even_when_enabled(monkeypatch):
    """Published metrics must not depend on a model's tool choices.

    Adversarial on purpose: aml_llm_planner is switched ON and the planner's
    LLM call is made to explode. run_agent_flags is expected to pin the flag
    off for the duration, so the run completes and the explosion never fires.
    If someone later re-points the harness at plan_query without pinning, this
    fails loudly instead of silently making the baseline nondeterministic.

    Runs the real pipeline once (~1 minute) — it is the only way to prove the
    guarantee end to end rather than by reading the source.
    """
    import backend.agent.llm_planner as llm_planner_mod
    from backend.config import settings
    from evaluation.run_evaluation import run_agent_flags

    def explode(*a, **kw):
        raise AssertionError("the evaluation harness reached the LLM planner")

    monkeypatch.setattr(settings, "aml_llm_planner", True)
    monkeypatch.setattr(llm_planner_mod, "complete_json", explode)

    any_flag, high_only, metrics = run_agent_flags(source="synthetic")

    assert any_flag, "expected the pipeline to still produce flags"
    assert high_only <= any_flag
    assert metrics.get("customer_count") == 270
    assert settings.aml_llm_planner is True, "run_agent_flags must restore the caller's setting"
